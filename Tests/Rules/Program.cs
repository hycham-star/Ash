using System;
using Ash;
int passed = 0;
void Check(bool condition, string name) { if (!condition) throw new Exception(name); passed++; Console.WriteLine("PASS " + name); }
var s = new Settlement();
s.Produce();
Check(s.Day == 2 && s.Supplies == 68 && s.Salvage == 56, "daily resource production");
s.BuildFarm();
Check(s.Farms == 2 && s.Salvage == 31, "farm cost and construction");
s.BuildWorkshop();
Check(s.Workshops == 2 && s.Supplies == 43 && s.Salvage == 11, "workshop cost and construction");
s.Recruit();
Check(s.Squad == 4 && s.Supplies == 23, "recruitment cost and squad growth");
s.AttackDepot();
Check(!s.OwnsDepot && s.Squad == 3 && s.Supplies == 8, "weak squad loses raid and pays cost");
s.AttackDepot();
Check(s.Squad == 3 && s.Supplies == 8, "insufficient supplies blocks raid without mutation");
s.BuildFarm(); s.BuildWorkshop(); s.Recruit(); s.BuildWatchtower();
Check(s.Salvage == 11 && s.Supplies == 8 && s.Farms == 2 && s.Workshops == 2 && s.Squad == 3 && s.Watchtowers == 0, "unaffordable actions preserve state");
var strong = new Settlement { Watchtowers = 2 };
strong.AttackDepot();
Check(strong.OwnsDepot && strong.Supplies == 45 && strong.Salvage == 85, "watchtowers contribute to successful capture");
strong.AttackDepot();
Check(strong.Supplies == 45 && strong.Salvage == 85, "captured depot cannot be farmed for repeat rewards");
strong.Produce();
Check(strong.Supplies == 65 && strong.Salvage == 91, "captured depot adds recurring income");
var weak = new Settlement { Squad = 1, Supplies = 100 };
weak.AttackDepot();
Check(weak.Squad == 1, "defeat preserves minimum squad");
Console.WriteLine($"{passed} checks passed");
